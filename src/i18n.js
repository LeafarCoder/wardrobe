const dictionaries = { "pt-PT": pt };
const listeners = new Set();

export function normalizeLocale(value) {
  return SUPPORTED_LOCALES.has(value) ? value : "en-US";
}

function storedLocale() {
  if (typeof localStorage === "undefined") return "en-US";
  return normalizeLocale(localStorage.getItem(STORAGE_KEY));
}

let currentLocale = storedLocale();

function updateDocumentLocale() {
  if (typeof document === "undefined") return;
  document.documentElement.lang = currentLocale;
  document.title = currentLocale === "pt-PT" ? pt.Wardrobe : "Wardrobe";
}

updateDocumentLocale();

export function getLocale() {
  return currentLocale;
}

export function setLocale(value, { persist = true } = {}) {
  const next = normalizeLocale(value);
  if (currentLocale === next) return next;
  currentLocale = next;
  if (persist && typeof localStorage !== "undefined") localStorage.setItem(STORAGE_KEY, next);
  updateDocumentLocale();
  listeners.forEach((listener) => listener());
  return next;
}

export function useLocale() {
  return useSyncExternalStore(
    (listener) => {
      listeners.add(listener);
      return () => listeners.delete(listener);
    },
    getLocale,
    () => "en-US",
  );
}

export function tr(key, values = {}) {
  const translated = dictionaries[currentLocale]?.[key] ?? key;
  const output = typeof translated === "function" ? translated(values) : translated;
  return String(output).replace(/\{(\w+)\}/g, (_, name) => values[name] ?? `{${name}}`);
}

export function hasTranslation(key, locale = "pt-PT") {
  return locale === "en-US" || Object.hasOwn(dictionaries[normalizeLocale(locale)] || {}, key);
}

export function formatNumber(value) {
  return new Intl.NumberFormat(currentLocale).format(value);
}

export function formatDate(value, options = { dateStyle: "medium" }) {
  const date = value instanceof Date ? value : new Date(value);
  return Number.isNaN(date.getTime()) ? String(value || "") : new Intl.DateTimeFormat(currentLocale, options).format(date);
}
